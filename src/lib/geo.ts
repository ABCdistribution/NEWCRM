/** Hash déterministe pour disperser les points d'une même ville (± ~1,5 km). */
function jitter(seed: string): [number, number] {
  let h = 7;
  for (const c of seed) h = (h * 31 + c.charCodeAt(0)) | 0;
  const a = ((h & 0xffff) / 0xffff - 0.5) * 0.028;
  const b = (((h >> 16) & 0x7fff) / 0x7fff - 0.5) * 0.028;
  return [a, b];
}

/** Coordonnées approximatives d'un point de vente — null si introuvable. */
export function geoloc(
  id: string,
  ville: string | null | undefined,
  codePostal: string | null | undefined,
): { lat: number; lng: number; approx: boolean } | null {
  const v = ville
    ?.toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/\s+\d+e?r?$/, '') // « Paris 15e » → « paris »
    .trim();
  const [ja, jb] = jitter(id);
  if (v) {
    const exact = VILLES[v] ?? VILLES[v.replace(/\s/g, '-')];
    if (exact) return { lat: exact[0] + ja, lng: exact[1] + jb, approx: false };
  }
  const dep = codePostal?.trim().slice(0, 2);
  if (dep && DEPARTEMENTS[dep]) {
    const d = DEPARTEMENTS[dep];
    return { lat: d[0] + ja * 4, lng: d[1] + jb * 4, approx: true };
  }
  return null;
}
