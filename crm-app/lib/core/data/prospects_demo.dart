}) => Prospect(
  id: id,
  nom: nom,
  raison: raison,
  classe: classe,
  cp: cp,
  statut: statut,
  pot: pot,
  proba: proba,
  contact: contact,
  timeline: tl,
  secteurId: secteur,
  cs: cs,
);

